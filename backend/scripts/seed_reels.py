#!/usr/bin/env python3
"""Bulk-seed processed HLS reel URLs from process_and_upload_reels.py's manifest."""

import argparse
import json
import os
import random
from pathlib import Path
from urllib.parse import urlparse
from uuid import UUID

from sqlalchemy import insert, select

from main import LegacyReels, Reels, SessionLocal, SocialProfiles


CAPTIONS = (
    "My gym membership includes free plot twists.",
    "Leg day said one more rep. My legs filed a complaint.",
    "POV: the dumbbell weighs more after you pick it up.",
    "Form was questionable. Confidence was undefeated.",
    "The rest timer ended. I respectfully ignored it.",
    "Gym math: one set left, repeated six times.",
    "Came for gains, stayed because the squat rack was occupied.",
    "That rep had a full character arc.",
    "When the warm-up is somehow the hardest set.",
    "Strong enough to lift it. Not strong enough to put it back quietly.",
)


def read_manifest(path: Path) -> list[dict[str, str]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    items = payload.get("items", []) if isinstance(payload, dict) else payload
    if not isinstance(items, list):
        raise ValueError("Manifest must be a JSON array of reel URL records")

    validated = []
    for item in items:
        if not isinstance(item, dict):
            raise ValueError("Each manifest entry must be an object")
        video_url = str(item.get("video_url", "")).strip()
        thumbnail_url = str(item.get("thumbnail_url", "")).strip()
        if urlparse(video_url).scheme != "https" or not video_url.endswith(".m3u8"):
            raise ValueError(f"Invalid HTTPS HLS playlist URL: {video_url}")
        if urlparse(thumbnail_url).scheme != "https":
            raise ValueError(f"Invalid HTTPS thumbnail URL: {thumbnail_url}")
        validated.append({"video_url": video_url, "thumbnail_url": thumbnail_url})
    return validated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path, help="JSON manifest generated by process_and_upload_reels.py")
    parser.add_argument("--creator-id", default=os.environ.get("REEL_CREATOR_ID"), help="Existing social_profiles.user_id; defaults to REEL_CREATOR_ID")
    parser.add_argument("--random-seed", type=int, default=7, help="Seed for repeatable initial engagement counts")
    args = parser.parse_args()

    entries = read_manifest(args.manifest)
    if not args.creator_id:
        parser.error("Pass --creator-id or set REEL_CREATOR_ID to an existing social profile UUID")
    try:
        creator_id = str(UUID(args.creator_id))
    except ValueError:
        parser.error("creator-id must be a valid UUID")

    randomizer = random.Random(args.random_seed)
    with SessionLocal() as session:
        creator = session.get(SocialProfiles, creator_id)
        if not creator:
            parser.error("creator-id must belong to an existing social profile")

        existing_urls = {
            url for url in session.scalars(select(Reels.video_url)) if url
        } | {
            url for url in session.scalars(select(Reels.video_hls_url)) if url
        }
        records = []
        for index, entry in enumerate(entries):
            if entry["video_url"] in existing_urls:
                continue
            records.append({
                **entry,
                "caption": CAPTIONS[index % len(CAPTIONS)],
                "creator_id": creator_id,
                "media_type": "video/mp4",
                "privacy": "public",
                "status": "ready",
                "seed_like_count": randomizer.randint(18, 420),
                "seed_comment_count": randomizer.randint(2, 58),
            })
            existing_urls.add(entry["video_url"])

        legacy_rows = list(session.scalars(select(LegacyReels)))
        migrated_legacy = 0
        for reel in legacy_rows:
            if reel.video_url in existing_urls:
                continue
            is_hls = reel.video_url.lower().endswith(".m3u8")
            records.append({
                "video_url": reel.video_url,
                "video_hls_url": reel.video_url if is_hls else None,
                "thumbnail_url": reel.thumbnail_url,
                "caption": reel.caption,
                "creator_id": creator_id,
                "media_type": "video/mp4",
                "privacy": "public",
                "status": "ready",
                "seed_like_count": reel.like_count,
                "seed_comment_count": reel.comment_count,
                "created_at": reel.created_at,
            })
            existing_urls.add(reel.video_url)
            migrated_legacy += 1

        if records:
            session.execute(insert(Reels), records)
            session.commit()
        print(f"Seeded {len(records)} reels, including {migrated_legacy} legacy rows; skipped existing URLs.")


if __name__ == "__main__":
    main()
